CREATE TABLE `trades` (
	`id` int AUTO_INCREMENT NOT NULL,
	`userId` int NOT NULL,
	`symbol` varchar(32) NOT NULL,
	`assetType` enum('Stocks','Crypto','Commodities/Futures') NOT NULL,
	`direction` enum('Long','Short') NOT NULL,
	`entryPrice` double NOT NULL,
	`exitPrice` double NOT NULL,
	`positionSize` double NOT NULL,
	`stopLoss` double NOT NULL,
	`takeProfit` double NOT NULL,
	`riskTradePct` double NOT NULL DEFAULT 1,
	`setup` varchar(80) NOT NULL,
	`chartUrl` varchar(500),
	`notes` text,
	`openedAt` timestamp NOT NULL,
	`closedAt` timestamp NOT NULL,
	`riskAmount` double NOT NULL,
	`rrRatio` double NOT NULL,
	`pnl` double NOT NULL,
	`rMultiple` double NOT NULL,
	`result` enum('win','loss','breakeven') NOT NULL,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	CONSTRAINT `trades_id` PRIMARY KEY(`id`)
);
